export function getLawById(id: string): Law | undefined {
  return laws.find((l) => l.id === id)
}

export function getLawsByCategory(categoryId: string): Law[] {
  return laws.filter((l) => l.category === categoryId)
}

export function searchLaws(query: string): Law[] {
  const q = query.toLowerCase()
  return laws.filter(
    (l) =>
      l.title.toLowerCase().includes(q) ||
      l.description.toLowerCase().includes(q) ||
      l.article.toLowerCase().includes(q) ||
      l.tags.some((t) => t.toLowerCase().includes(q)) ||
      l.fullText.toLowerCase().includes(q)
  )
}

